_RENAMED = {"waves": "wave", "sparkle": "star", "dices": "dice"}
KINDS = {_RENAMED.get(icon, icon): icon for icon in _ENTRIES}
WORDS = {_RENAMED.get(icon, icon): tuple(words.split()) for icon, words in _ENTRIES.items()}
# Pronouns and broad nouns that only illustrate a line when nothing more concrete does.
WEAK_WORDS = frozenset({"you", "us", "away", "day", "world", "words"})


def _word_kinds(words):
    """Invert kind -> words, refusing a word that two kinds claim."""
    result = {}
    for kind, group in words.items():
        for word in group:
            if word in result:
                raise ValueError(f"{word!r} is listed twice, under {result[word]} and {kind}")
            result[word] = kind
    return result


WORD_KINDS = _word_kinds(WORDS)
