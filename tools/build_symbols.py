"""Bundle the Lucide icons Halo uses into halo/lucide_data.py.

Usage: python tools/build_symbols.py <lucide-static-package-dir>

The folder is the extracted lucide-static package (the one holding icons/ and package.json).
Only its SVG files and version are read; nothing from the package is run.
"""
import json
import sys
from pathlib import Path
from xml.etree import ElementTree

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "halo" / "lucide_data.py"
# Geometry attributes kept per supported element; paint attributes are dropped.
GEOMETRY = {
    "path": ("d",),
    "circle": ("cx", "cy", "r"),
    "ellipse": ("cx", "cy", "rx", "ry"),
    "rect": ("x", "y", "width", "height", "rx", "ry"),
    "line": ("x1", "y1", "x2", "y2"),
    "polyline": ("points",),
    "polygon": ("points",),
}
HEADER = '''"""Generated by tools/build_symbols.py from lucide-static; do not edit.

Lucide is ISC licensed, see third_party/lucide/LICENSE.
"""
'''


class IconError(Exception):
    """One or more icons cannot be bundled."""


def find_package(folder):
    """Return the folder holding icons/ and package.json, given it or its parent."""
    folder = Path(folder)
    for candidate in (folder, folder / "package"):
        if (candidate / "icons").is_dir() and (candidate / "package.json").is_file():
            return candidate
    raise IconError(f"{folder} is not a lucide-static package: expected icons/ and package.json")


def parse_icon(name, text):
    """Read one Lucide SVG into (tag, attrs) pairs; anything beyond plain shapes raises IconError."""
    if "<!DOCTYPE" in text or "<!ENTITY" in text:
        raise IconError(f"{name}: SVG declares a DOCTYPE or entity")
    try:
        root = ElementTree.fromstring(text)
    except ElementTree.ParseError as error:
        raise IconError(f"{name}: not valid SVG ({error})") from error
    if root.tag.rpartition("}")[2] != "svg" or root.get("viewBox") != "0 0 24 24":
        raise IconError(f"{name}: expected an <svg> with viewBox 0 0 24 24")
    elements = []
    for child in root:
        tag = child.tag.rpartition("}")[2]
        if tag not in GEOMETRY:
            raise IconError(f"{name}: unsupported element <{tag}>")
        if "transform" in child.attrib:
            raise IconError(f"{name}: <{tag}> has a transform")
        elements.append((tag, {key: child.attrib[key] for key in GEOMETRY[tag] if key in child.attrib}))
    return tuple(elements)


def check_icon(name, elements):
    """Return the reasons an icon breaks the no-enclosing-shape rule, or an empty list."""
    problems = []
    if name.startswith(("circle-", "square-")):
        problems.append(f"{name}: enclosing shape by name")
    if not elements:
        problems.append(f"{name}: has no shapes")
    for tag, attrs in elements:
        size = {key: float(attrs.get(key, 0)) for key in ("r", "rx", "ry", "width", "height")}
        if tag == "circle" and size["r"] >= 9:
            problems.append(f"{name}: circle of radius {size['r']:g} encloses the icon")
        elif tag == "ellipse" and max(size["rx"], size["ry"]) >= 9:
            problems.append(f"{name}: ellipse of radius {max(size['rx'], size['ry']):g} encloses the icon")
        elif tag == "rect" and min(size["width"], size["height"]) >= 18:
            problems.append(f"{name}: {size['width']:g} by {size['height']:g} rectangle encloses the icon")
    return problems


def render(version, icons):
    """Write the module source for icons, a mapping of name to elements, in sorted order."""
    lines = [HEADER.rstrip("\n"), f"LUCIDE_VERSION = {json.dumps(version)}", "", "ICONS = {"]
    for name in sorted(icons):
        lines.append(f"    {json.dumps(name)}: (")
        for tag, attrs in icons[name]:
            pairs = ", ".join(f"{json.dumps(key)}: {json.dumps(value)}" for key, value in attrs.items())
            lines.append(f"        ({json.dumps(tag)}, {{{pairs}}}),")
        lines.append("    ),")
    lines.append("}")
    return "\n".join(lines) + "\n"


def build(package_dir, names):
    """Return the lucide_data module source for the named icons, or raise IconError listing every problem."""
    package = find_package(package_dir)
    version = json.loads((package / "package.json").read_text(encoding="utf-8"))["version"]
    icons, problems = {}, []
    for name in sorted(set(names)):
        file = package / "icons" / f"{name}.svg"
        if not file.is_file():
            problems.append(f"{name}: no such icon in Lucide {version}")
            continue
        try:
            icons[name] = parse_icon(name, file.read_text(encoding="utf-8"))
        except IconError as error:
            problems.append(str(error))
            continue
        problems.extend(check_icon(name, icons[name]))
    if problems:
        raise IconError("cannot bundle these icons:\n" + "\n".join(f"  {problem}" for problem in problems))
    return render(version, icons)


def main(argv=None):
    args = sys.argv[1:] if argv is None else argv
    if len(args) != 1:
        print(__doc__.split("\n\n")[1], file=sys.stderr)
        return 2
    sys.path.insert(0, str(ROOT))
    from halo.symbol_lexicon import KINDS
    try:
        source = build(args[0], KINDS.values())
    except IconError as error:
        print(f"error: {error}", file=sys.stderr)
        return 1
    OUTPUT.write_text(source, encoding="utf-8", newline="\n")
    print(f"Wrote {OUTPUT.relative_to(ROOT)} with {len(set(KINDS.values()))} icons")
    return 0


if __name__ == "__main__":
    sys.exit(main())
